#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

SHERPA_ONNX_SRC="${SHERPA_ONNX_SRC:-$HOME/jetson-voice-assistant-runtime-dev/sherpa-onnx}"
BUILD_DIR="$SHERPA_ONNX_SRC/build"

FLAGS_FILE="$BUILD_DIR/sherpa-onnx/csrc/CMakeFiles/sherpa-onnx-vad-alsa-offline-asr.dir/flags.make"

OUT_DIR="$SCRIPT_DIR/build"
SRC="$SCRIPT_DIR/smart_turn_probe.cc"
OBJ="$OUT_DIR/smart_turn_probe.o"
BIN="$OUT_DIR/smart_turn_probe"

if [[ ! -d "$SHERPA_ONNX_SRC" ]]; then
    echo "ERROR: sherpa-onnx source not found:"
    echo "  $SHERPA_ONNX_SRC"
    exit 1
fi

if [[ ! -f "$FLAGS_FILE" ]]; then
    echo "ERROR: runtime build flags not found:"
    echo "  $FLAGS_FILE"
    echo
    echo "Build sherpa-onnx runtime first."
    exit 1
fi

if [[ ! -f "$SRC" ]]; then
    echo "ERROR: probe source not found:"
    echo "  $SRC"
    exit 1
fi

mkdir -p "$OUT_DIR"

CXX_DEFINES="$(sed -n 's/^CXX_DEFINES = //p' "$FLAGS_FILE")"
CXX_INCLUDES="$(sed -n 's/^CXX_INCLUDES = //p' "$FLAGS_FILE")"
CXX_FLAGS="$(sed -n 's/^CXX_FLAGS = //p' "$FLAGS_FILE")"

echo "=========================================="
echo " M06 Smart Turn Probe Build"
echo "=========================================="
echo "Source       : $SRC"
echo "Sherpa source: $SHERPA_ONNX_SRC"
echo "Sherpa build : $BUILD_DIR"
echo "Output       : $BIN"
echo

echo "[1/2] Compile"

# Intentionally use word splitting here because these values are the
# compiler flag lists generated by CMake in flags.make.
# shellcheck disable=SC2086
/usr/bin/c++ \
    $CXX_DEFINES \
    $CXX_INCLUDES \
    $CXX_FLAGS \
    -c "$SRC" \
    -o "$OBJ"

echo "[2/2] Link"

(
    cd "$BUILD_DIR/sherpa-onnx/csrc"

    /usr/bin/c++ \
        -static-libstdc++ \
        -static-libgcc \
        -O3 \
        -DNDEBUG \
        "$OBJ" \
        -o "$BIN" \
        ../../lib/libsherpa-onnx-core.a \
        -lasound \
        ../../lib/libkaldi-native-fbank-core.a \
        ../../lib/libkissfft-float.a \
        ../../lib/libkaldi-decoder-core.a \
        ../../lib/libsherpa-onnx-kaldifst-core.a \
        ../../lib/libssentencepiece_core.a \
        -lpthread \
        ../../_deps/onnxruntime-src/lib/libonnxruntime.a \
        -lm \
        ../../lib/libsherpa-onnx-fstfar.a \
        ../../lib/libsherpa-onnx-fst.a \
        -ldl \
        ../../lib/libpiper_phonemize.a \
        ../../lib/libespeak-ng.a \
        -lm \
        ../../lib/libucd.a \
        -ldl \
        -pthread
)

echo
echo "BUILD PASS"
echo "Binary: $BIN"
